/// 상태 효과 (기획서 §3.4).
///
/// **12종을 넘기지 않는다.** 세로 화면에서 아이콘 12개가 물리적 한계다(§3.4).
/// 그래서 이 enum은 의도적으로 닫혀 있다. 새 상태를 넣고 싶으면
/// 기존 것을 하나 빼야 한다.
///
/// M0에서 실제 규칙이 붙은 것은 [strength] · [vulnerable] · [weak] · [poison] ·
/// [grudge] 다섯 개다. 나머지는 이름만 자리를 잡아 두었고,
/// 카드가 요구할 때 엔진에 규칙을 붙인다.
library;

enum StatusId {
  /// 기세 — 공격 피해 +n. 감소하지 않는다.
  strength,

  /// 굳음 — 방어 카드의 방어도 +n. 감소하지 않는다.
  dexterity,

  /// 취약 — 받는 피해 +50%. 턴마다 1 감소.
  vulnerable,

  /// 약화 — 주는 피해 -25%. 턴마다 1 감소.
  weak,

  /// 중독 — 자기 턴 시작 시 n 피해, 이후 1 감소.
  poison,

  /// 화상 — 턴 종료 시 n 피해. (M0 미구현)
  burn,

  /// 재생 — 턴 시작 시 n 회복. (M0 미구현)
  regen,

  /// 속박 — 카드 사용 불가. (M0 미구현)
  bind,

  /// 무형 — 받는 피해를 1로 고정. (M0 미구현)
  intangible,

  /// 통찰 — 드로우 +n. (M0 미구현)
  insight,

  /// 침묵 — 특정 카드 봉인. (M0 미구현)
  silence,

  /// 원한 — 업 비례 피해. 업 축(§3.3)에 직접 얹힌 유일한 상태다.
  grudge,
}

/// 효과가 누구에게 향하는지.
///
/// §7.3의 카드 JSON에는 이 필드가 없다. 대부분의 경우 연산자로 유추되기
/// 때문이다 — 피해는 대상에게, 방어는 자신에게. 다만 상태 부여만은
/// 갈리므로(원한은 적에게, 기세는 자신에게) 명시할 수단을 둔다.
enum EffectTarget {
  /// 카드가 지정한 적.
  enemy,

  /// 카드를 쓴 본인.
  self,
}
